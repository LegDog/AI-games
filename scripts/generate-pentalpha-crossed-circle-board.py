"""Generate original board artwork, topology and movement geometry together."""
import argparse
import math
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent / 'pentalpha-crossed-circle'
TAU = math.tau
RADIUS = .76

def vertex(k):
    a = TAU*k/5-math.pi/2
    return math.cos(a), math.sin(a)

def quadratic(a,b,t):
    # Control point a+b produces the five outward bowed star paths.
    u=1-t
    return tuple(u*u*a[j]+2*u*t*(a[j]+b[j])+t*t*b[j] for j in range(2))

def bisect(fn,lo,hi):
    for _ in range(80):
        mid=(lo+hi)/2
        if fn(lo)*fn(mid)<=0: hi=mid
        else: lo=mid
    return (lo+hi)/2

def pixel(p): return 251+218*p[0],251+218*p[1]
def pair(p): return '{'+','.join(f'{v:.12f}' for v in pixel(p))+'}'
def generate():
    vertices=[vertex(k) for k in range(5)]
    paths=[]; params=[]; points={k:v for k,v in enumerate(vertices)}
    a,b=vertices[0],vertices[2]
    t_circle=bisect(lambda t: math.hypot(*quadratic(a,b,t))-RADIUS,0,.5)
    angle=-math.pi/2+TAU/10
    t_inner=bisect(lambda t: quadratic(a,b,t)[0]*math.sin(angle)-quadratic(a,b,t)[1]*math.cos(angle),0,.5)
    ts=[0,t_circle,t_inner,.5,1-t_inner,1-t_circle,1]
    for k in range(5):
        ids=[k,5+(4*k+1)%20,25+(2*k+1)%10,25+(2*k+2)%10,25+(2*k+3)%10,5+(4*k+7)%20,(k+2)%5]
        paths.append(ids); params.append(ts)
        for p,t in zip(ids,ts):
            xy=quadratic(vertices[k],vertices[(k+2)%5],t)
            if p in points: assert math.dist(points[p],xy)<1e-8
            points[p]=xy
    # Even circle positions are the endpoints of five diameters.
    for k in range(10):
        angle=-math.pi/2+TAU*k/10
        points[5+2*k]=(RADIUS*math.cos(angle),RADIUS*math.sin(angle))
    points[35]=(0,0)
    for k in range(5):
        ids=[5+2*k,25+k,35,25+(k+5)%10,5+(2*k+10)%20]
        paths.append(ids)
        start,end=points[ids[0]],points[ids[-1]]
        length=math.dist(start,end)
        params.append([math.dist(start,points[p])/length for p in ids])
        for p,t in zip(ids,params[-1]):
            assert math.dist(points[p],tuple(start[j]+t*(end[j]-start[j]) for j in range(2)))<1e-8
    paths.append(list(range(5,25)))
    circle_t=[]
    for p in paths[-1]:
        angle=(math.atan2(points[p][1],points[p][0])+math.pi/2)%TAU
        if abs(angle-TAU)<1e-8:angle=0
        circle_t.append(angle/TAU)
    assert circle_t==sorted(circle_t)
    params.append(circle_t)
    moves=[]; intervals=[]
    for index,ids in enumerate(paths):
        closed=index==10
        for start in range(len(ids) if closed else len(ids)-2):
            positions=[(start+j)%len(ids) for j in range(3)]
            triple=[ids[p] for p in positions]
            t0=params[index][positions[0]]
            t1=params[index][positions[2]]+(1 if closed and positions[2]<positions[0] else 0)
            moves.extend([(*triple,index),(*reversed(triple),index)])
            intervals.extend([(t0,t1),(t1,t0)])
    assert len(points)==36 and len(moves)==120
    assert len({(a,c) for a,b,c,p in moves})==120
    labels=[f'v{k}' for k in range(5)]+[f'r{k}' for k in range(20)]+[f'i{k}' for k in range(10)]+['c']
    header='// Generated by scripts/generate-pentalpha-crossed-circle-board.py; GPL-3.0-or-later\n'
    game=header+'const char * const game_labels[GAME_POINTS] = {'+','.join(f'"{s}"' for s in labels)+'};\n'
    game+='const unsigned game_path_lengths[GAME_PATHS] = {'+','.join(str(len(p)) for p in paths)+'};\n'
    game+='const unsigned game_lines[GAME_PATHS][GAME_PATH_POINTS] = {\n'+',\n'.join('{'+','.join(map(str,p))+'}' for p in paths)+'\n};\n'
    game+='const Move game_moves[GAME_CHOICES] = {\n'+',\n'.join('{'+','.join(map(str,m))+'}' for m in moves)+'\n};\n'
    board=header+'const BoardPoint board_points[GAME_POINTS] = {\n'+',\n'.join(pair(points[k]) for k in range(36))+'\n};\n'
    geometry=[]
    svgpaths=[]
    for k in range(5):
        a,b=vertices[k],vertices[(k+2)%5]; control=tuple(a[j]+b[j] for j in range(2))
        geometry.append('{'+','.join([pair(a),pair(control),pair(b),'FALSE'])+'}')
        ap,cp,bp=map(pixel,[a,control,b])
        svgpaths.append(f'<path d="M {ap[0]:.9f},{ap[1]:.9f} Q {cp[0]:.9f},{cp[1]:.9f} {bp[0]:.9f},{bp[1]:.9f}"/>')
    for k in range(5,10):
        a,b=points[paths[k][0]],points[paths[k][-1]];control=tuple((a[j]+b[j])/2 for j in range(2))
        geometry.append('{'+','.join([pair(a),pair(control),pair(b),'FALSE'])+'}')
        ap,bp=map(pixel,[a,b]);svgpaths.append(f'<path d="M {ap[0]:.9f},{ap[1]:.9f} L {bp[0]:.9f},{bp[1]:.9f}"/>')
    geometry.append('{{0,0},{0,0},{0,0},TRUE}')
    board+='const BoardPath board_paths[GAME_PATHS] = {\n'+',\n'.join(geometry)+'\n};\n'
    board+='static const double move_parameters[GAME_CHOICES][2] = {\n'+',\n'.join('{'+f'{a:.14f},{b:.14f}'+'}' for a,b in intervals)+'\n};\n'
    svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 502 502">\n<rect width="502" height="502" rx="24" fill="#11121e"/>\n<g fill="none" stroke="#aaa1e7" stroke-width="2.2">\n'+'\n'.join(svgpaths)+f'\n<circle cx="251" cy="251" r="{218*RADIUS}"/>\n</g>\n'
    svg+='<g fill="#242638" stroke="#d6b85a" stroke-width="1.5">\n'+ '\n'.join(f'<circle cx="{pixel(points[k])[0]:.9f}" cy="{pixel(points[k])[1]:.9f}" r="9"/>' for k in range(36))+'\n</g></svg>\n'
    return {'src/game-data.inc':game,'src/board-data.inc':board,'data/board.svg':svg,'data/io.github.aigames.PentalphaCrossedCircle.svg':svg}

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,data in generate().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=data:raise SystemExit(f'Out of date: {path}')
        else:path.write_text(data)
    print('Crossed Circle: 36 points, 11 paths, 120 directed placements verified')
if __name__=='__main__':main()
