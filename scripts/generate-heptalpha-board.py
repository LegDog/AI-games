"""Generate original curved artwork and authoritative Heptalpha path data.

No runtime/build dependency: outputs are checked in. --check detects drift.
Each quadratic connects vertex k to k+3; its control point is four times
its endpoint midpoint relative to the center. Numerical intersections are
refined with Newton iteration, then saved with their path parameters.
"""
import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / 'heptalpha'

def add(a, b): return (a[0] + b[0], a[1] + b[1])
def sub(a, b): return (a[0] - b[0], a[1] - b[1])
def mul(a, s): return (a[0] * s, a[1] * s)
def cross(a, b): return a[0] * b[1] - a[1] * b[0]
def evaluate(path, t):
    a, c, b = path
    return add(add(mul(a, (1-t)**2), mul(c, 2*(1-t)*t)), mul(b, t*t))
def derivative(path, t):
    a, c, b = path
    return mul(add(mul(sub(c, a), 1-t), mul(sub(b, c), t)), 2)
def pixel(p): return (251 + 218 * p[0], 251 + 218 * p[1])
def pair(p): return '{%.12f, %.12f}' % p

def generate():
    vertices = [(math.sin(2*math.pi*k/7), -math.cos(2*math.pi*k/7)) for k in range(7)]
    paths = [(vertices[k], mul(add(vertices[k], vertices[(k+3)%7]), 2), vertices[(k+3)%7]) for k in range(7)]
    samples = [[evaluate(path, j/96) for j in range(97)] for path in paths]
    intersections = []
    for i in range(7):
        for j in range(i):
            hits = []
            for ia in range(96):
                a, b = samples[i][ia:ia+2]; u = sub(b, a)
                for ja in range(96):
                    c, d = samples[j][ja:ja+2]; v = sub(d, c); denominator = cross(u, v)
                    if abs(denominator) < 1e-12: continue
                    t = cross(sub(c, a), v)/denominator
                    s = cross(sub(c, a), u)/denominator
                    if not (0 <= t <= 1 and 0 <= s <= 1): continue
                    t, s = (ia+t)/96, (ja+s)/96
                    for _ in range(12):
                        delta = sub(evaluate(paths[j], s), evaluate(paths[i], t))
                        u, v = derivative(paths[i], t), derivative(paths[j], s)
                        determinant = cross(u, v)
                        t += cross(delta, v)/determinant
                        s += cross(delta, u)/determinant
                    if not (1e-7 < t < 1-1e-7 and 1e-7 < s < 1-1e-7): continue
                    if any(abs(t - old[0]) < 1e-7 for old in hits): continue
                    hits.append((t, s))
            for t, s in hits:
                p = evaluate(paths[i], t)
                assert math.dist(p, evaluate(paths[j], s)) < 1e-9
                angle = math.atan2(p[0], -p[1]) % (2*math.pi)
                if angle > 2*math.pi-1e-9: angle = 0
                intersections.append((angle, p, i, t, j, s))
    intersections.sort()
    assert len(intersections) == 14
    points = vertices + [item[1] for item in intersections]
    labels = [f'v{k+1}' for k in range(7)] + [f'i{k+1}' for k in range(14)]
    ordered = [[(0., k), (1., (k+3)%7)] for k in range(7)]
    for number, (_, _, i, t, j, s) in enumerate(intersections, 7):
        ordered[i].append((t, number)); ordered[j].append((s, number))
    for line in ordered:
        line.sort(); assert len(line) == 6
    moves = []
    for path, line in enumerate(ordered):
        for offset in range(4):
            a, b, c = [entry[1] for entry in line[offset:offset+3]]
            moves.extend(((a,b,c,path), (c,b,a,path)))
    assert len(moves) == len(set((a,c) for a,b,c,p in moves)) == 56
    output = '// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by scripts/generate-heptalpha-board.py; do not edit.\n'
    output += 'const char * const game_labels[GAME_POINTS] = {' + ', '.join(f'"{x}"' for x in labels) + '};\n'
    output += 'const unsigned game_lines[GAME_PATHS][GAME_PATH_POINTS] = {\n'
    output += ''.join('    {' + ', '.join(str(p) for t,p in line) + '},\n' for line in ordered) + '};\n'
    output += 'const Move game_moves[GAME_CHOICES] = {\n' + ''.join('    {%u, %u, %u, %u},\n' % m for m in moves) + '};\n'
    output += 'const BoardPoint board_points[GAME_POINTS] = {\n' + ''.join('    '+pair(pixel(p))+',\n' for p in points) + '};\n'
    output += 'const BoardPath board_paths[GAME_PATHS] = {\n'
    for path, line in zip(paths, ordered):
        output += '    {' + ', '.join(pair(pixel(p)) for p in path) + ', {' + ', '.join('%.15f'%t for t,p in line) + '}},\n'
    output += '};\n'
    svg = '<!-- SPDX-License-Identifier: GPL-3.0-or-later -->\n<!-- Original project artwork; generated by scripts/generate-heptalpha-board.py. -->\n'
    svg += '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 502 502">\n'
    svg += '<circle cx="251" cy="251" r="244" fill="none" stroke="#d4af37" stroke-width="2" opacity=".65"/>\n'
    for k, path in enumerate(paths):
        a,c,b = map(pixel, path)
        svg += f'<path id="path-{k+1}" d="M{a[0]:.12f},{a[1]:.12f} Q{c[0]:.12f},{c[1]:.12f} {b[0]:.12f},{b[1]:.12f}" fill="none" stroke="#e0e0e0" stroke-width="3.5"/>\n'
    for label, point in zip(labels, points):
        x,y = pixel(point)
        svg += f'<circle id="node-{label}" cx="{x:.12f}" cy="{y:.12f}" r="10" fill="#2c2c35" stroke="#d4af37" stroke-width="2.5"/>\n'
    svg += '</svg>\n'
    return {ROOT/'src/board-data.inc': output, ROOT/'data/board.svg': svg}

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, data in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != data: raise SystemExit(f'Stale generated board: {path}')
        else: path.write_text(data)
    print('Heptalpha geometry: 21 points, seven six-point paths, 56 directed placements verified')
